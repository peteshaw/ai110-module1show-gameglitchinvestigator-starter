def parse_guess(raw: str, low: int | None = None, high: int | None = None):
    """Parse the player's input into an integer guess.

    Decimals are truncated toward zero, so "7.9" becomes 7.

    Args:
        raw: The text the player typed. May be None or empty.
        low: Smallest allowed guess. The range is only checked when both
            low and high are given.
        high: Largest allowed guess.

    Returns:
        A tuple (ok, guess, error). On success it is (True, guess, None);
        on failure it is (False, None, message to show the player).
    """
    if raw is None or raw == "":
        return False, None, "Enter a guess."

    try:
        if "." in raw:
            value = int(float(raw))
        else:
            value = int(raw)
    except (TypeError, ValueError, OverflowError):
        return False, None, "That is not a number."

    if low is not None and high is not None and not low <= value <= high:
        return False, None, f"Guess must be between {low} and {high}."

    return True, value, None


