def check_guess(guess, secret):
    """Compare a guess to the secret number.

    Both values are converted to int first, so numeric strings compare by
    value ("10" is higher than "2").

    Args:
        guess: The player's guess, as an int or numeric string.
        secret: The secret number, as an int or numeric string.

    Returns:
        "Win", "Too High", or "Too Low".
    """
    guess_value = int(guess)
    secret_value = int(secret)

    if guess_value == secret_value:
        return "Win"
    if guess_value > secret_value:
        return "Too High"
    return "Too Low"


