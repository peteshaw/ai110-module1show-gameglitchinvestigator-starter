def get_range_for_difficulty(difficulty: str):
    """Return the inclusive range the secret number is picked from.

    Args:
        difficulty: "Easy", "Normal", or "Hard".

    Returns:
        A (low, high) tuple. Unknown difficulties use the Hard range.
    """
    if difficulty == "Easy":
        return 1, 20
    if difficulty == "Normal":
        return 1, 50
    if difficulty == "Hard":
        return 1, 100
    return 1, 100


def get_attempt_limit(difficulty: str):
    """Return the number of guesses allowed for a difficulty.

    Args:
        difficulty: "Easy", "Normal", or "Hard".

    Returns:
        The attempt limit. Unknown difficulties use the Normal limit.
    """
    if difficulty == "Easy":
        return 8
    if difficulty == "Normal":
        return 6
    if difficulty == "Hard":
        return 4
    return 6


