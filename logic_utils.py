def update_score(current_score: int, outcome: str, attempt_number: int):
    """Return the new score after a guess.

    A win earns 100 - 10 * attempt_number points, with a minimum of 10.
    A wrong guess, too high or too low, subtracts 5.

    Args:
        current_score: The score before this guess.
        outcome: The result from check_guess.
        attempt_number: How many guesses have been made, including this one.

    Returns:
        The updated score. Unknown outcomes leave it unchanged.
    """
    if outcome == "Win":
        points = 100 - 10 * attempt_number
        if points < 10:
            points = 10
        return current_score + points

    if outcome in ("Too High", "Too Low"):
        return current_score - 5

    return current_score
